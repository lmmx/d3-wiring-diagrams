// Bundle CodeMirror (codemirror.entry.js) into viewer/vendor/codemirror.js.
//
//   npm run vendor            # rewrite the bundle
//   npm run vendor -- --check # exit 1 if the committed bundle is not what the lockfile builds
//
// The bundle is committed, like the vendored d3, so the viewer runs from a plain
// checkout (`just serve`) with no build step. The versions are the exact ones in
// package.json and package-lock.json, and CI checks the bundle against them.

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, "../viewer/vendor");
const ENTRY = path.join(HERE, "codemirror.entry.js");

const lock = JSON.parse(readFileSync(path.join(HERE, "package-lock.json"), "utf8"));

const bundle = await build({
  entryPoints: [ENTRY],
  bundle: true,
  format: "esm",
  minify: true,
  legalComments: "none",
  target: "es2022",
  write: false,
  metafile: true,
});
// the packages that went into the bundle, with their locked versions
const packages = new Set(
  Object.keys(bundle.metafile.inputs).flatMap((f) => f.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/)?.[1] ?? []),
);
const versions = [...packages].sort().map((p) => `${p}@${lock.packages[`node_modules/${p}`].version}`);
const banner = `// CodeMirror 6, bundled by site/vendor.mjs (MIT licence, https://codemirror.net). Do not edit.\n// ${versions.join(" ")}\n`;
const files = new Map([
  [path.join(OUT, "codemirror.js"), banner + bundle.outputFiles[0].text],
  [path.join(OUT, "codemirror.d.ts"), `// Types of viewer/vendor/codemirror.js: generated by site/vendor.mjs from site/codemirror.entry.js.\n${readFileSync(ENTRY, "utf8")}`],
]);

const check = process.argv.includes("--check");
let stale = 0;
for (const [file, text] of files) {
  let current = "";
  try {
    current = readFileSync(file, "utf8");
  } catch {}
  if (current === text) continue;
  stale++;
  console.log(`${check ? "stale" : "written"}: ${path.relative(path.join(HERE, ".."), file)}`);
  if (!check) writeFileSync(file, text);
}
if (check && stale) process.exit(1);
